def put(bus, t, x, db=0.0, p=0.0):
    x = np.asarray(x, float)
    if x.ndim == 1:
        th = (float(np.clip(p, -1, 1)) + 1) * np.pi / 4
        x = np.stack([x * np.cos(th), x * np.sin(th)]) * np.sqrt(2)
    place(bus, x, t, dbg(db))


def nrm(x, peak=1.0):
    return x / (np.max(np.abs(x)) + 1e-12) * peak


def env_seg(n, a, d):
    e = np.ones(n)
    na, nd = ns(a), ns(d)
    if na > 0:
        e[:na] = np.linspace(0, 1, na)
    if nd > 0:
        e[-nd:] *= np.linspace(1, 0, nd)
    return e


# ---------------------------------------------------------------- generators
def thud(r, f=90.0, dur=0.22, noise=0.25, f_noise=900.0):
    t = tt(dur)
    y = np.sin(phase(f * (1 + 0.6 * np.exp(-t / 0.02)))) * np.exp(-t / (dur / 5))
    y += noise * lp(r.standard_normal(len(t)), f_noise) * np.exp(-t / 0.02)
    return fades(y, 0.001, 0.02)


def click(r, f=3000.0, dur=0.02):
    t = tt(dur)
    return hp(r.standard_normal(len(t)), f) * np.exp(-t / 0.003)


def rustle(dur, r, dens=90.0, lo=1800, hi=9000):
    n = ns(dur)
    base = bp(r.standard_normal(n), lo, hi, 1) * 0.25
    m = np.zeros(n)
    for tm in r.uniform(0, dur, int(dens * dur)):
        k = ns(tm)
        L = ns(r.uniform(0.004, 0.02))
        m[k:k + L] += r.uniform(0.3, 1.0) * np.exp(-np.arange(min(L, n - k)) / (L / 3))
    am = smooth_noise(n, r, 9.0)
    return fades(base * (0.4 + 0.6 * np.abs(am)) + hp(r.standard_normal(n), 2500) * m * 0.9, 0.01, 0.06)


def ding(f=1318.5, dur=0.9):
    t = tt(dur)
    return (np.sin(TAU * f * t) + 0.3 * np.sin(TAU * 2.76 * f * t)) * np.exp(-t / 0.28) * env_seg(len(t), 0.002, 0.05)


def metal_rip(r, dur=1.4):
    """fuselage tearing apart: ringing metal modes, a ripping noise burst and a low boom"""
    n = ns(dur)
    t = np.arange(n) / SR
    rip = bp(r.standard_normal(n), 800, 6000, 1) * (np.exp(-t / 0.45) * (0.6 + 0.4 * np.abs(smooth_noise(n, r, 25))))
    ring = modal(dur, [(220, 1, 0.5), (587, 0.8, 0.35), (1310, 0.6, 0.25), (2740, 0.4, 0.15)], r)[:n]
    boom = np.sin(phase(60 * (1 + 0.5 * np.exp(-t / 0.05)))) * np.exp(-t / 0.5) * 1.6
    wind = lp(colored(n, r, 1.0), 1500) * np.clip(t / 0.3, 0, 1) * 0.6
    return fades(nrm(rip * 0.9 + ring * 0.5 + boom + wind), 0.002, 0.3)


def groan(dur, r, f0=70.0, f1=110.0, level=1.0):
    """pressure groan of a hull: slow stick-slip metal creak, rising"""
    n = ns(dur)
    t = np.arange(n) / SR
    f = f0 + (f1 - f0) * (t / dur)
    y = np.zeros(n)
    ph = phase(f)
    for h in range(1, 10):
        y += np.sin(h * ph + h) / h ** 1.1
    y = bp(y, 120, 1400, 1) * (0.5 + 0.5 * np.abs(smooth_noise(n, r, 7.0))) * np.clip(t / (dur * 0.6), 0, 1)
    return fades(nrm(y) * level, 0.05, 0.12)


def hiss(dur, r, lo=2500, hi=9000, shape_pts=None):
    n = ns(dur)
    t = np.arange(n) / SR
    y = bp(r.standard_normal(n), lo, hi, 1)
    e = np.interp(t, *(zip(*shape_pts))) if shape_pts else np.ones(n)
    return fades(nrm(y) * e, 0.01, 0.05)


def crack_snap(r):
    n = ns(0.5)
    t = np.arange(n) / SR
    y = hp(r.standard_normal(n), 1800) * np.exp(-t / 0.004) + modal(0.5, [(2100, 1, 0.05), (4300, 0.6, 0.03), (7000, 0.4, 0.02)], r)[:n] * 0.5
    y += np.sin(phase(150 * (1 + 0.5 * np.exp(-t / 0.02)))) * np.exp(-t / 0.08)
    return fades(nrm(y), 0.0003, 0.1)


def pencil(dur, r):
    n = ns(dur)
    t = np.arange(n) / SR
    strokes = (np.sin(TAU * 5 * t) > 0.2).astype(float)
    y = bp(r.standard_normal(n), 2500, 7500, 1) * uniform_filter1d(strokes, ns(0.01)) * (0.5 + 0.5 * np.abs(smooth_noise(n, r, 12)))
    return fades(nrm(y) * 0.5, 0.02, 0.05)


# ================================================================ AMBIENCE beds (own file)
def amb(t0, t1, gen, db=0.0, fi=0.5, fo=0.5):
    n = ns(t1 - t0)
    x = np.asarray(gen(t1 - t0), float)
    x = x[:, :n] if x.ndim == 2 else np.stack([x[:n], x[:n]])
    e = np.ones(x.shape[1])
    a, b = min(ns(fi), len(e)), min(ns(fo), len(e))
    e[:a] = np.linspace(0, 1, a)
    e[len(e) - b:] *= np.linspace(1, 0, b)
    place(AMB, x * e, t0, dbg(db))


def cabin(d, jet=1.0, murmur=0.0):
    """pressurised cabin: low engine rumble + air noise (+ distant passengers)"""
    r = R()
    n = ns(d)
    rum = lp(colored(n, r, 2.0), 220) * 0.9
    air = bp(colored(n, r, 0.8), 400, 3200, 1) * 0.12
    whine = np.sin(TAU * 410 * np.arange(n) / SR) * 0.012
    y = (rum + air + whine) * jet
    if murmur:
        y = y + bp(colored(n, r, 1.0), 180, 1600, 1) * (0.4 + 0.6 * np.abs(smooth_noise(n, r, 1.5))) * 0.12 * murmur
    return np.stack([y, np.roll(y, 17)])


def sky(d):
    r = R()
    return G.breeze(d, r, 1.5, 0.3, 1400) + np.stack([lp(colored(ns(d), r, 2.0), 180)] * 2) * 0.5


def hangar(d, water=0.0):
    r = R()
    n = ns(d)
    y = lp(colored(n, r, 1.8), 350) * 0.4 + np.sin(TAU * 60 * np.arange(n) / SR) * 0.03
    x = np.stack([y, np.roll(y, 41)])
    if water:
        x = x + G.water_bed(d, R(), 0.7, 0.5)[:, :n] * water
    return x


def room(d):
    r = R()
    n = ns(d)
    y = lp(colored(n, r, 1.5), 400) * 0.18
    return np.stack([y, np.roll(y, 11)])


