# master for the composition: normalised to -14 LUFS, peaks above 0.6 are soft-knee limited (tanh) to stay under -1 dBFS
def soft_limit(x, knee=0.6, ceil=dbg(-1.0)):
    a = np.abs(x)
    over = a > knee
    y = x.copy()
    y[over] = np.sign(x[over]) * (knee + (ceil - knee) * np.tanh((a[over] - knee) / (ceil - knee)))
    return y


