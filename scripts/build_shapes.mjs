// Builds src/kit/data/shapes.ts from characters/shapes/headN.svg and bodyN.svg (N = 1, 2, 3, ... any number; new files are picked up by re-running this script).
// Only the main closed <path> of each SVG is used (the first <path d="...">). Background rects, <image> elements and fills are ignored (the SVG fills are placeholders).
// Each path is flattened to a polygon, resampled to N points by arc length, and normalised to its own bounding box: y in [0, 1] (top 0, bottom 1), x centred, width = aspect (width / height).
// Usage: node scripts/build_shapes.mjs
import fs from 'node:fs';
import path from 'node:path';
const dir = path.resolve('characters/shapes'), out = path.resolve('src/kit/data/shapes.ts'), N = 128;

function flatten(d) { // M L H V C S Q T Z (absolute and relative); arcs are approximated by a straight line to the end point
  const t = [...d.matchAll(/([a-zA-Z])|(-?\d*\.?\d+(?:e[-+]?\d+)?)/gi)].map((m) => m[1] ?? parseFloat(m[2]));
  const pts = []; let i = 0, cmd = '', x = 0, y = 0, sx = 0, sy = 0, cx = 0, cy = 0, pc = '';
  const num = () => t[i++];
  const cubic = (x0, y0, x1, y1, x2, y2, x3, y3) => { for (let k = 1; k <= 24; k++) { const u = k / 24, m = 1 - u; pts.push([m * m * m * x0 + 3 * m * m * u * x1 + 3 * m * u * u * x2 + u * u * u * x3, m * m * m * y0 + 3 * m * m * u * y1 + 3 * m * u * u * y2 + u * u * u * y3]); } };
  while (i < t.length) {
    if (typeof t[i] === 'string') cmd = t[i++];
    const rel = cmd === cmd.toLowerCase(), C = cmd.toUpperCase(), ox = rel ? x : 0, oy = rel ? y : 0;
    if (C === 'M') { x = ox + num(); y = oy + num(); sx = x; sy = y; pts.push([x, y]); cmd = rel ? 'l' : 'L'; pc = 'M'; continue; }
    if (C === 'L') { x = ox + num(); y = oy + num(); pts.push([x, y]); }
    else if (C === 'H') { x = (rel ? x : 0) + num(); pts.push([x, y]); }
    else if (C === 'V') { y = (rel ? y : 0) + num(); pts.push([x, y]); }
    else if (C === 'C') { const x1 = ox + num(), y1 = oy + num(), x2 = ox + num(), y2 = oy + num(), x3 = ox + num(), y3 = oy + num(); cubic(x, y, x1, y1, x2, y2, x3, y3); cx = x2; cy = y2; x = x3; y = y3; }
    else if (C === 'S') { const x1 = pc === 'C' || pc === 'S' ? 2 * x - cx : x, y1 = pc === 'C' || pc === 'S' ? 2 * y - cy : y, x2 = ox + num(), y2 = oy + num(), x3 = ox + num(), y3 = oy + num(); cubic(x, y, x1, y1, x2, y2, x3, y3); cx = x2; cy = y2; x = x3; y = y3; }
    else if (C === 'Q') { const qx = ox + num(), qy = oy + num(), x3 = ox + num(), y3 = oy + num(); cubic(x, y, x + (2 / 3) * (qx - x), y + (2 / 3) * (qy - y), x3 + (2 / 3) * (qx - x3), y3 + (2 / 3) * (qy - y3), x3, y3); x = x3; y = y3; }
    else if (C === 'A') { i += 5; x = ox + num(); y = oy + num(); pts.push([x, y]); }
    else if (C === 'Z') { x = sx; y = sy; }
    else { i++; }
    pc = C;
  }
  return pts;
}
function resample(p, n) { // by arc length, closed
  const q = [...p, p[0]], len = [0]; for (let i = 1; i < q.length; i++) len.push(len[i - 1] + Math.hypot(q[i][0] - q[i - 1][0], q[i][1] - q[i - 1][1]));
  const L = len[len.length - 1], o = []; let j = 1;
  for (let k = 0; k < n; k++) { const s = (k / n) * L; while (len[j] < s) j++; const a = q[j - 1], b = q[j], u = (s - len[j - 1]) / (len[j] - len[j - 1] || 1); o.push([a[0] + (b[0] - a[0]) * u, a[1] + (b[1] - a[1]) * u]); }
  return o;
}
const result = {heads: [], bodies: []};
for (const kind of ['head', 'body']) {
  const files = fs.readdirSync(dir).filter((f) => new RegExp(`^${kind}\\d+\\.svg$`).test(f)).sort((a, b) => parseInt(a.replace(/\D/g, '')) - parseInt(b.replace(/\D/g, '')));
  for (const f of files) {
    const svg = fs.readFileSync(path.join(dir, f), 'utf8'), m = svg.match(/<path\b[^>]*?\sd="([^"]+)"/);
    if (!m) { console.warn(`[shapes] ${f}: no <path d>, skipped`); continue; }
    const poly = resample(flatten(m[1]), N), xs = poly.map((p) => p[0]), ys = poly.map((p) => p[1]), x0 = Math.min(...xs), x1 = Math.max(...xs), y0 = Math.min(...ys), y1 = Math.max(...ys), h = y1 - y0, aspect = (x1 - x0) / h;
    const pts = poly.map((p) => [+((p[0] - (x0 + x1) / 2) / h).toFixed(5), +((p[1] - y0) / h).toFixed(5)]);
    result[kind === 'head' ? 'heads' : 'bodies'].push({name: f.replace('.svg', ''), aspect: +aspect.toFixed(4), pts});
    console.log(`[shapes] ${f}: ${poly.length} points, aspect ${aspect.toFixed(3)}`);
  }
}
fs.writeFileSync(out, `// GENERATED by scripts/build_shapes.mjs from characters/shapes/*.svg (main closed path only). Do not edit.\n// pts: closed polygon, y in [0, 1] (top 0, bottom 1), x centred on the bounding box, width = aspect.\nexport interface DrawnShape { name: string; aspect: number; pts: [number, number][] }\nexport const SHAPES: {heads: DrawnShape[]; bodies: DrawnShape[]} = ${JSON.stringify(result)};\n`);
console.log(`[shapes] wrote ${out}: ${result.heads.length} heads, ${result.bodies.length} bodies`);
