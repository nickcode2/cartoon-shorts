// Usage: node scripts/build_map_data.mjs <110m|50m> <out.ts|out.json> [Country Name,Country Name,...]
// Downloads Natural Earth via world-atlas (TopoJSON), decodes it and writes {name: [polygon[ring[[lon,lat]]]]}.
// Source: https://github.com/topojson/world-atlas (Natural Earth, public domain). Use 110m for world views, 50m for zoomed countries.
import fs from 'node:fs';
const [res = '110m', out = 'src/kit/data/countries110.ts', names] = process.argv.slice(2);
const url = `https://cdn.jsdelivr.net/npm/world-atlas@2/countries-${res}.json`;
const topo = await (await fetch(url)).json();
const {scale, translate} = topo.transform;
const arcs = topo.arcs.map((a) => {
  let x = 0, y = 0;
  return a.map(([dx, dy]) => [(x += dx) * scale[0] + translate[0], (y += dy) * scale[1] + translate[1]]);
});
const ring = (idx) => idx.flatMap((i, k) => {
  const pts = i >= 0 ? arcs[i] : arcs[~i].slice().reverse();
  return k ? pts.slice(1) : pts;
}).map(([x, y]) => [+x.toFixed(2), +y.toFixed(2)]);
const want = names ? new Set(names.split(',')) : null;
const res2 = {};
for (const g of topo.objects.countries.geometries) {
  const n = g.properties.name;
  if (want && !want.has(n)) continue;
  const polys = g.type === 'Polygon' ? [g.arcs] : g.type === 'MultiPolygon' ? g.arcs : [];
  res2[n] = polys.map((p) => p.map(ring));
}
const body = JSON.stringify(res2);
fs.writeFileSync(out, out.endsWith('.ts') ? `// generated by scripts/build_map_data.mjs (Natural Earth ${res} via world-atlas). Do not edit.\nconst data: Record<string, number[][][][]> = ${body};\nexport default data;\n` : body);
console.log(res, Object.keys(res2).length, 'countries', (fs.statSync(out).size / 1024).toFixed(0) + 'KB');
